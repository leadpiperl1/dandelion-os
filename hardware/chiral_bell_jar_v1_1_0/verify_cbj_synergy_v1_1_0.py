#!/usr/bin/env python3
"""
verify_cbj_synergy_v1_1_0.py
Parses OpenSCAD CBJ_CAD_LUT telemetry, audits 21-port mechanical clearances,
and emits Q2.14/Q3.13 C99 header cbj_cad_trim_lut_v1_1_0.h (--seed 42).
Author: Justin D. Grimm (ORCID: 0009-0000-5299-0243) | Version: v1.1.0
"""

import argparse
import hashlib
import math
import random
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

C_M_PER_S     = 299_792_458.0
F0_HZ         = 915.0e6
LAMBDA0_MM    = (C_M_PER_S / F0_HZ) * 1000.0  # 327.642031 mm
R_IN_MM       = 143.10
R_BOSS_NOM_MM = 178.00
SPLIT_DEG     = 72.00
DN16CF_OD_MM  = 33.78
R_HELM_MM     = 220.00
Z_HELM_MM     = 110.00
COIL_H_MM     = 28.00

ECHO_RE = re.compile(
    r'ECHO:\s*"CBJ_CAD_LUT"\s*,\s*(\d+)\s*,\s*([-+0-9.eE]+)\s*,\s*([-+0-9.eE]+)'
)


def extract_openscad_lut(scad_path: Path, force_headless: bool, seed: int, cnc_tol_mm: float):
    rng = random.Random(seed)
    openscad_bin = None if force_headless else shutil.which("openscad")
    rows = {}

    if openscad_bin and scad_path.exists():
        with tempfile.TemporaryDirectory() as tmpdir:
            csg_out = Path(tmpdir) / "cbj_probe.csg"
            proc = subprocess.run(
                [openscad_bin, "-o", str(csg_out), str(scad_path)],
                capture_output=True,
                text=True,
                timeout=30,
                check=True,
            )
            combined = (proc.stdout or "") + "\n" + (proc.stderr or "")
            for match in ECHO_RE.finditer(combined):
                k = int(match.group(1))
                az_deg = float(match.group(2))
                r_mm = float(match.group(3))
                rows[k] = (az_deg, r_mm)
        source_mode = "openscad-csg"
    else:
        for k in range(13):
            az_deg = k * (360.0 / 13.0)
            rows[k] = (az_deg, R_BOSS_NOM_MM)
        source_mode = "parametric-headless-fallback"

    if sorted(rows.keys()) != list(range(13)):
        raise RuntimeError(f"Expected 13 equatorial probes (0..12), got {sorted(rows.keys())}")

    final_lut = []
    for k in range(13):
        az_deg, r_base = rows[k]
        delta_cnc = rng.uniform(-cnc_tol_mm, cnc_tol_mm) if cnc_tol_mm > 0.0 else 0.0
        final_lut.append((k, az_deg, r_base + delta_cnc))
    return final_lut, source_mode


def audit_mechanical_clearances(lut_rows):
    expected_step = 360.0 / 13.0
    for k, az_deg, r_mm in lut_rows:
        if abs(az_deg - k * expected_step) > 1e-3:
            raise AssertionError(f"Probe P{k:02d} azimuth drift: {az_deg:.4f} deg")
        if abs(r_mm - R_BOSS_NOM_MM) > 2.0:
            raise AssertionError(f"Probe P{k:02d} boss radius out of bounds: {r_mm:.3f} mm")

    boss_chord_mm = 2.0 * R_BOSS_NOM_MM * math.sin(math.pi / 13.0)
    wrench_gap_mm = boss_chord_mm - DN16CF_OD_MM
    if wrench_gap_mm < 30.0:
        raise AssertionError(f"Insufficient DN16CF wrench clearance: {wrench_gap_mm:.2f} mm")

    z_split_mm = R_IN_MM * math.cos(math.radians(SPLIT_DEG))
    collar_clear_mm = z_split_mm - (DN16CF_OD_MM / 2.0)
    if collar_clear_mm < 25.0:
        raise AssertionError(f"Parting plane too close to probe flange: {collar_clear_mm:.2f} mm")

    z_coil_inner_mm = Z_HELM_MM - (COIL_H_MM / 2.0)
    coil_clear_mm = z_coil_inner_mm - (DN16CF_OD_MM / 2.0)
    if coil_clear_mm < 60.0:
        raise AssertionError(f"Helmholtz bobbin interference: {coil_clear_mm:.2f} mm")

    return wrench_gap_mm, collar_clear_mm, coil_clear_mm


def quantize_q14_lut(lut_rows):
    entries = []
    for k, az_deg, r_mm in lut_rows:
        delta_r = r_mm - R_BOSS_NOM_MM
        dtheta = (2.0 * math.pi * delta_r) / LAMBDA0_MM
        dtheta = (dtheta + math.pi) % (2.0 * math.pi) - math.pi

        cos_q14 = int(round(math.cos(dtheta) * 16384.0))
        sin_q14 = int(round(math.sin(dtheta) * 16384.0))
        dphi_q13 = int(round(dtheta * 8192.0))

        norm_err = abs((cos_q14 * cos_q14 + sin_q14 * sin_q14) - (16384 * 16384)) / float(16384 * 16384)
        if norm_err > 2.5e-4:
            raise AssertionError(f"Q2.14 rotation norm drift on P{k:02d}: {norm_err:.3e}")

        entries.append((k, az_deg, r_mm, dtheta, cos_q14, sin_q14, dphi_q13))
    return entries


def write_c99_trim_header(entries, header_path: Path, seed: int, source_mode: str):
    digest_src = "|".join(f"{k}:{c}:{s}:{p}" for k, _, _, _, c, s, p in entries).encode("utf-8")
    lut_sha = hashlib.sha256(digest_src).hexdigest()[:16]

    lines = [
        "#ifndef CBJ_CAD_TRIM_LUT_V1_1_0_H",
        "#define CBJ_CAD_TRIM_LUT_V1_1_0_H",
        "",
        f"/* Auto-generated by verify_cbj_synergy_v1_1_0.py (--seed {seed}, mode={source_mode}) */",
        f"/* LUT SHA-256[0..15]: {lut_sha} | f0 = 915.0 MHz | lambda0 = {LAMBDA0_MM:.6f} mm */",
        "",
        "#undef CBJ_CAD_TRIM_LUT_INIT",
        "#define CBJ_CAD_TRIM_LUT_INIT { \\",
    ]
    for k, az_deg, r_mm, _, cos_q14, sin_q14, dphi_q13 in entries:
        comma = "," if k < 12 else " "
        lines.append(
            f"    {{ {cos_q14:6d}, {sin_q14:6d}, {dphi_q13:6d} }}{comma} "
            f"/* P{k:02d}: az={az_deg:7.3f} deg, R={r_mm:7.3f} mm */ \\"
        )
    lines.extend([
        "}",
        "",
        "#ifdef CBJ_TEST_FLOAT_REF",
        "static const double g_cbj_ref_dtheta_rad[13] = {",
    ])
    for k, _, _, dtheta, _, _, _ in entries:
        comma = "," if k < 12 else ""
        lines.append(f"    {dtheta:+.12e}{comma}")
    lines.extend([
        "};",
        "#endif /* CBJ_TEST_FLOAT_REF */",
        "",
        "#endif /* CBJ_CAD_TRIM_LUT_V1_1_0_H */",
        "",
    ])
    header_path.write_text("\n".join(lines), encoding="utf-8")
    return lut_sha


def main():
    ap = argparse.ArgumentParser(description="Chiral Bell Jar CAD-to-C99 Verification Gate (v1.1.0)")
    ap.add_argument("--scad", type=Path, default=Path("cbj_vessel_v1_1_0.scad"))
    ap.add_argument("--header-out", type=Path, default=Path("cbj_cad_trim_lut_v1_1_0.h"))
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--cnc-tol-mm", type=float, default=0.12)
    ap.add_argument("--headless-cad", action="store_true")
    args = ap.parse_args()

    lut_rows, mode = extract_openscad_lut(args.scad, args.headless_cad, args.seed, args.cnc_tol_mm)
    wrench_mm, collar_mm, coil_mm = audit_mechanical_clearances(lut_rows)
    entries = quantize_q14_lut(lut_rows)
    lut_sha = write_c99_trim_header(entries, args.header_out, args.seed, mode)

    print(
        f"[PASS] Gate G0 CAD Audit ({mode}): wrench={wrench_mm:.2f} mm, "
        f"collar={collar_mm:.2f} mm, helmholtz={coil_mm:.2f} mm"
    )
    print(
        f"[PASS] Emitted {args.header_out} (SHA={lut_sha}, tol=+/-{args.cnc_tol_mm:.2f} mm)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
